// Shared invoice-creation primitives (used by routes/invoices.js and lib/autoBilling.js).

async function generateInvoiceNumber(client) {
  // The sequence can lag behind numbers already used (restored/seeded data): skip taken numbers.
  for (let i = 0; i < 100000; i++) {
    const seq = await client.query(`SELECT nextval('invoice_number_seq') AS n`);
    const num = `INV-${String(Number(seq.rows[0].n)).padStart(6, '0')}`;
    const taken = await client.query(`SELECT 1 FROM invoices WHERE invoice_number = $1`, [num]);
    if (taken.rows.length === 0) return num;
  }
  throw new Error('Could not allocate a free invoice number.');
}

// Inserts one 'unpaid' invoice with a fresh number and the customer-number
// snapshot. ON CONFLICT DO NOTHING makes the auto-billing unique indexes a
// hard idempotency guard: returns the row, or null if a conflict swallowed it.
async function insertInvoice(client, { customerId, batchCustomerId = null, total, discount = 0, currency = 'USD',
  zoneNameSnapshot = null, notes = null, createdBy, billingPeriod = null, autoGenerated = false }) {
  const invoiceNumber = await generateInvoiceNumber(client);
  const r = await client.query(
    `INSERT INTO invoices (invoice_number, customer_id, batch_customer_id, invoice_total, discount_amount, currency, status,
       zone_name_snapshot, notes, created_by, customer_number_snapshot, billing_period, auto_generated)
     VALUES ($1,$2,$3,$4,$5,$6,'unpaid',$7,$8,$9,(SELECT customer_number FROM customers WHERE id = $2),$10,$11)
     ON CONFLICT DO NOTHING RETURNING *`,
    [invoiceNumber, customerId, batchCustomerId, total, discount, currency, zoneNameSnapshot, notes, createdBy, billingPeriod, autoGenerated]
  );
  if (r.rows[0]) return r.rows[0];
  // A conflict swallowed the insert. Only the auto-billing idempotency indexes may legitimately do
  // that; confirm the invoice really exists, otherwise surface it (e.g. a number collision).
  let exists = false;
  if (billingPeriod) {
    exists = (await client.query(`SELECT 1 FROM invoices WHERE customer_id = $1 AND billing_period = $2 AND status <> 'voided'`, [customerId, billingPeriod])).rows.length > 0;
  } else if (batchCustomerId) {
    exists = (await client.query(`SELECT 1 FROM invoices WHERE batch_customer_id = $1 AND status <> 'voided'`, [batchCustomerId])).rows.length > 0;
  }
  if (!exists) throw new Error('Invoice insert conflicted but no existing invoice found (invoice number collision?)');
  return null;
}

module.exports = { generateInvoiceNumber, insertInvoice };
